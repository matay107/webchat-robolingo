import "server-only";
import { z } from "zod";

/**
 * Server configuration, validated once at first use so a misconfigured deployment
 * fails fast with an actionable message instead of misbehaving at runtime.
 */
export interface Env {
  lineChannelSecret: string;
  lineChannelAccessToken: string;
  databaseUrl: string;
  adminPasswordHash: string;
  sessionSecret: string;
}

const envSchema = z.object({
  LINE_CHANNEL_SECRET: z.string().regex(/^[0-9a-f]{32}$/i, "must be the 32-char hex channel secret"),
  LINE_CHANNEL_ACCESS_TOKEN: z.string().min(20, "must be a channel access token"),
  DATABASE_URL: z.string().regex(/^postgres(ql)?:\/\//, "must be a postgres:// connection string"),
  ADMIN_PASSWORD_HASH: z.string().startsWith("scrypt:", "must be generated by `pnpm hash-password`"),
  SESSION_SECRET: z.string().min(32, "must be at least 32 characters"),
});

export function parseEnv(source: Record<string, string | undefined>): Env {
  const result = envSchema.safeParse(source);
  if (!result.success) {
    // Report variable names and rules only: values may be secrets (ASVS V7.1.1).
    const problems = result.error.issues.map((issue) => {
      const reason = issue.code === "invalid_type" ? "is required" : issue.message;
      return `${issue.path.join(".")} ${reason}`;
    });
    throw new Error(`Invalid environment configuration:\n- ${problems.join("\n- ")}`);
  }

  const env = result.data;
  return {
    lineChannelSecret: env.LINE_CHANNEL_SECRET,
    lineChannelAccessToken: env.LINE_CHANNEL_ACCESS_TOKEN,
    databaseUrl: env.DATABASE_URL,
    adminPasswordHash: env.ADMIN_PASSWORD_HASH,
    sessionSecret: env.SESSION_SECRET,
  };
}

let cached: Env | undefined;

/** Lazily validated `process.env`; lazy so `next build` does not need runtime secrets. */
export function getEnv(): Env {
  cached ??= parseEnv(process.env);
  return cached;
}
